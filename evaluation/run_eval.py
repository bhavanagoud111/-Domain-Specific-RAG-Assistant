"""Phase 4 — evaluate the graph over ``evaluation/eval_set.json`` against the FROZEN corpus.

Measures, per question and in aggregate:

  1. RETRIEVAL PRECISION  — of the chunks retrieved, how many are relevant to the question,
     and was the expected country actually retrieved.
  2. ANSWER FAITHFULNESS  — is every claim in the answer supported by a chunk it cites.
  3. GATE CORRECTNESS     — did the citation gate pass/fail appropriately; in particular do
     the deliberately-unanswerable questions correctly resolve 0 citations.

REPEATED SAMPLING (Week 6 amendment)
------------------------------------
Week 6 Phase 1d established that the gate is **nondeterministic at the boundary**: the UAE
passed 3/3 in Week 5 and failed 3/4 in Week 6 with a frozen corpus and unchanged code, because
generation runs at ``temperature=0.3`` and UAE's tourism chunks are page chrome plus a bare
district-name list. Single-run numbers on marginal countries are therefore not trustworthy.

Sampling is concentrated where flips actually happen rather than paid for uniformly:

  * ``thin``-tier countries (<30 chunks) and ALL unanswerable questions -> **3 runs**
  * ``rich`` and ``mid`` tier                                          -> **1 run**

A question "flipped" if its gate verdict (>=1 citation vs 0 citations) is not identical
across all of its runs. The flip count is a headline number, not a footnote.

JUDGE INDEPENDENCE AND BLINDING
-------------------------------
Answers are generated by ``openai/gpt-4o`` (graph GEN_MODEL). Judging them with gpt-4o would
be a model grading its own output, so the judge is ``anthropic/claude-sonnet-4.5`` -- a
different vendor, not merely a different size of the same family.

The judge is also **blinded**: its prompts contain only the question, the chunk text, and the
answer text. No prompt names the generator, the judge, the project, or any model. See
``assert_judge_blinded()``, which fails the run if a model identifier ever reaches the judge.

The judge is itself audited -- ``evaluation/verify_judge.py`` samples verdicts for hand-checking
against raw chunk text.

Checkpointed to ``evaluation/eval_results.json`` after every run; re-running resumes.

Run:  PYTHONPATH=. python evaluation/run_eval.py
"""

from __future__ import annotations

import json
import re
import statistics
from pathlib import Path
from typing import Any

import requests

from config import settings
from graph.wanderrag_graph import run_query

JUDGE_MODEL = "anthropic/claude-sonnet-4.5"
HERE = Path(__file__).resolve().parent
EVAL_SET = HERE / "eval_set.json"
RESULTS = HERE / "eval_results.json"

RUNS_THIN = 3   # thin tier + unanswerable: sampled repeatedly to expose gate flips
RUNS_RICH = 1   # rich/mid tier: single run

# Unambiguous model/vendor identifiers. Deliberately EXCLUDES bare words that occur
# legitimately in travel text -- "llama" (Peru), "mistral" (a Mediterranean wind), "gemini"
# -- because this check is run against text we do not control and a false positive would
# abort a valid evaluation.
_MODEL_TOKENS = re.compile(
    r"gpt-?4|gpt-?3|openai|anthropic|claude|wanderrag|GEN_MODEL|FAST_MODEL|"
    r"language model|as an AI\b",
    re.I,
)


def assert_judge_blinded(prompt: str, generated_answer: str = "") -> None:
    """Fail loudly if a model/system identifier would reach the judge.

    Scans the prompt SCAFFOLDING and the generated answer -- i.e. the parts whose wording
    this project controls -- but not the corpus chunk text pasted into the prompt. Retrieved
    chunks are third-party travel copy; scanning them would fail on legitimate content
    (Peru's tourism chunks say "llama") without telling us anything about blinding, since
    the corpus is identical no matter which model generated the answer.
    """
    for label, text in (("prompt scaffolding", prompt.split("CHUNKS:")[0].split("CITED CHUNKS:")[0]),
                        ("generated answer", generated_answer)):
        leaks = set(_MODEL_TOKENS.findall(text))
        if leaks:
            raise AssertionError(
                f"JUDGE BLINDING VIOLATION in {label} -- leaks model identity: {sorted(leaks)}"
            )


def _judge(prompt: str, max_tokens: int = 1200, generated_answer: str = "") -> dict[str, Any]:
    assert_judge_blinded(prompt, generated_answer)
    key = settings.require_openrouter_key()
    r = requests.post(
        f"{settings.OPENROUTER_BASE_URL}/chat/completions",
        headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"},
        json={"model": JUDGE_MODEL, "messages": [{"role": "user", "content": prompt}],
              "max_tokens": max_tokens, "temperature": 0},
        timeout=180,
    )
    r.raise_for_status()
    raw = r.json()["choices"][0]["message"]["content"].strip()
    m = re.search(r"\{.*\}", raw, re.S)
    if not m:
        return {"_parse_error": raw[:500]}
    try:
        return json.loads(m.group(0))
    except json.JSONDecodeError:
        return {"_parse_error": raw[:500]}


RELEVANCE_PROMPT = """You are scoring a retrieval system. For the question below, decide for
EACH retrieved chunk whether it is RELEVANT -- i.e. whether it contains information a person
would actually use to answer that question.

Be strict. Navigation menus, page headers/footers, cookie notices, lists of unrelated country
names, and generic boilerplate are NOT relevant even if they mention the right country.
A chunk about visa rules is NOT relevant to a "what should I visit" question, and vice versa.

QUESTION: {q}

CHUNKS:
{chunks}

Reply with ONLY this JSON:
{{"verdicts": [{{"chunk": 1, "relevant": true, "why": "<8 words>"}}, ...]}}"""


FAITHFULNESS_PROMPT = """You are auditing whether an answer is grounded in the sources it cites.

Break the ANSWER into its distinct factual claims (ignore hedging and filler). For each claim,
decide whether it is SUPPORTED by the text of the chunk(s) the answer cites.

A claim is supported ONLY if the cited chunk text actually states it. If the chunk merely
mentions a place name and the answer asserts something *about* that place that the chunk does
not state, the claim is NOT supported. Plausible real-world truth is irrelevant -- judge only
against the chunk text.

QUESTION: {q}

ANSWER:
{answer}

CITED CHUNKS:
{chunks}

Reply with ONLY this JSON:
{{"claims": [{{"claim": "<short>", "supported": true, "why": "<10 words>"}}, ...]}}"""


def runs_for(item: dict[str, Any]) -> int:
    """Thin tier and unanswerable questions get repeated sampling; rich/mid get one run."""
    if item["question_type"] == "unanswerable" or item["corpus_tier"] == "thin":
        return RUNS_THIN
    return RUNS_RICH


def one_run(item: dict[str, Any], run_idx: int) -> dict[str, Any]:
    q = item["question"]
    state = run_query(q, run_id=f"eval_{abs(hash(q)) % 10**8}_{run_idx}")

    retrieved = state.get("retrieved_chunks", []) or []
    citations = state.get("citations", []) or []
    n_cits = state.get("citations_resolved", len(citations))
    expected = item["expected_country"]

    rec: dict[str, Any] = {
        "run": run_idx,
        "final_answer": state.get("final_answer", ""),
        "citations_resolved": n_cits,
        "low_confidence": bool(state.get("low_confidence")),
        "thin_pass": bool(state.get("thin_pass")),
        "retries": state.get("retry_count", 0),
        "n_retrieved": len(retrieved),
        "retrieved_chunks_text": [
            f"(country={c.get('country')}, source={c.get('source_type')}, "
            f"score={round(float(c.get('score', 0)), 3)})\n{(c.get('text') or '')[:1500]}"
            for c in retrieved
        ],
        "citations_text": [
            f"[{c.get('marker')}] (country={c.get('country')}, source={c.get('source_type')})\n"
            f"{(c.get('text') or '')[:1500]}" for c in citations
        ],
    }

    # ---- 1. retrieval precision + country correctness ----------------------
    if retrieved:
        blob = "\n\n".join(
            f"[chunk {i+1}] (country={c.get('country')}, source={c.get('source_type')})\n"
            f"{(c.get('text') or '')[:900]}" for i, c in enumerate(retrieved))
        v = _judge(RELEVANCE_PROMPT.format(q=q, chunks=blob))
        verdicts = v.get("verdicts", [])
        rel = [bool(x.get("relevant")) for x in verdicts]
        rec["retrieval"] = {
            "n": len(retrieved), "n_judged": len(rel), "n_relevant": sum(rel),
            "precision": round(sum(rel) / len(rel), 4) if rel else None,
            "verdicts": verdicts,
            "country_match_rate": round(
                sum(1 for c in retrieved if c.get("country") == expected) / len(retrieved), 4),
            "expected_country_retrieved": any(c.get("country") == expected for c in retrieved),
            "countries_seen": sorted({c.get("country") for c in retrieved}),
        }
    else:
        rec["retrieval"] = {"n": 0, "precision": None, "expected_country_retrieved": False,
                            "country_match_rate": None, "verdicts": [], "countries_seen": []}

    # ---- 2. faithfulness ---------------------------------------------------
    if citations:
        cited_blob = "\n\n".join(
            f"[{c.get('marker')}] (country={c.get('country')}, source={c.get('source_type')})\n"
            f"{(c.get('text') or '')[:900]}" for c in citations)
        v = _judge(FAITHFULNESS_PROMPT.format(
            q=q, answer=rec["final_answer"][:2500], chunks=cited_blob),
            generated_answer=rec["final_answer"][:2500])
        claims = v.get("claims", [])
        sup = [bool(c.get("supported")) for c in claims]
        rec["faithfulness"] = {
            "n_claims": len(sup), "n_supported": sum(sup),
            "score": round(sum(sup) / len(sup), 4) if sup else None, "claims": claims,
        }
    else:
        rec["faithfulness"] = {"n_claims": 0, "n_supported": 0, "score": None, "claims": []}

    # ---- 3. gate correctness ----------------------------------------------
    gate_passed = n_cits >= 1
    correct = gate_passed if item["answerable"] else (not gate_passed)
    rec["gate"] = {
        "passed": gate_passed, "correct": correct,
        "expectation": "expected >=1 citation" if item["answerable"] else "expected 0 citations",
        "citations_resolved": n_cits,
    }
    return rec


def eval_item(item: dict[str, Any]) -> dict[str, Any]:
    n = runs_for(item)
    runs = [one_run(item, i + 1) for i in range(n)]

    gates = [r["gate"]["passed"] for r in runs]
    flipped = len(set(gates)) > 1

    def mean(vals: list[float | None]) -> float | None:
        xs = [v for v in vals if v is not None]
        return round(statistics.mean(xs), 4) if xs else None

    return {
        "question": item["question"],
        "expected_country": item["expected_country"],
        "question_type": item["question_type"],
        "corpus_tier": item["corpus_tier"],
        "answerable": item["answerable"],
        "reference_answer": item.get("reference_answer"),
        "n_runs": n,
        "runs": runs,
        # Aggregates across this question's runs.
        "gate_verdicts": gates,
        "gate_flipped": flipped,
        "gate_correct_rate": round(sum(1 for r in runs if r["gate"]["correct"]) / n, 4),
        "mean_citations": round(statistics.mean([r["citations_resolved"] for r in runs]), 4),
        "mean_precision": mean([r["retrieval"]["precision"] for r in runs]),
        "mean_faithfulness": mean([r["faithfulness"]["score"] for r in runs]),
        "expected_country_retrieved_rate": round(
            sum(1 for r in runs if r["retrieval"]["expected_country_retrieved"]) / n, 4),
    }


def main() -> None:
    data = json.loads(EVAL_SET.read_text(encoding="utf-8"))
    items = data["items"]

    done: dict[str, Any] = {}
    if RESULTS.exists():
        prev = json.loads(RESULTS.read_text(encoding="utf-8"))
        done = {r["question"]: r for r in prev.get("results", [])}
        print(f"[resume] {len(done)} questions already done")

    total_runs = sum(runs_for(i) for i in items)
    print(f"[plan] {len(items)} questions -> {total_runs} graph runs "
          f"(thin+unanswerable x{RUNS_THIN}, rich/mid x{RUNS_RICH})")

    results = []
    for i, item in enumerate(items, 1):
        q = item["question"]
        if q in done:
            results.append(done[q])
            continue
        try:
            rec = eval_item(item)
        except Exception as exc:
            rec = {"question": q, "expected_country": item["expected_country"],
                   "question_type": item["question_type"], "corpus_tier": item["corpus_tier"],
                   "answerable": item["answerable"], "error": f"{type(exc).__name__}: {exc}"}
        results.append(rec)
        RESULTS.write_text(json.dumps(
            {"judge_model": JUDGE_MODEL, "judge_blinded": True,
             "runs_thin": RUNS_THIN, "runs_rich": RUNS_RICH,
             "corpus_points_count": data.get("corpus_points_count"),
             "results": results}, indent=2, ensure_ascii=False), encoding="utf-8")
        flag = "FLIP" if rec.get("gate_flipped") else "    "
        print(f"  [{i}/{len(items)}] {flag} {item['question_type']:<14} "
              f"{item['expected_country']:<22} {item['corpus_tier']:<5} "
              f"cits={rec.get('gate_verdicts')} prec={rec.get('mean_precision')} "
              f"faith={rec.get('mean_faithfulness')} gate={rec.get('gate_correct_rate')}")

    print(f"\nwrote {RESULTS}  ({len(results)} questions)")


if __name__ == "__main__":
    main()
